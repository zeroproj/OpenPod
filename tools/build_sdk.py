#!/usr/bin/env python3
"""build_sdk.py - build the OpenPod Reload 3.1 C SDK with zig cc.

Usage:
    python3 tools/build_sdk.py --variante diag
    python3 tools/build_sdk.py --variante jogos --check-repro

The result is sdk/build/app.bin (linked at 0xDAB000) plus app.json with the
hook symbol.  The code has no .data/.bss and is reproducible: the same
sources and ziglang version must give the same bytes.
"""
import argparse
import hashlib
import json
import os
import shutil
import struct
import subprocess
import sys

RAIZ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SDK = os.path.join(RAIZ, "sdk")
BASE = 0x00DAB000
FLASH = 0x00C00000
HOOK = "hook_home_menu_create"

COMMON = ["-mthumb", "-Os", "-std=c11", "-ffreestanding", "-fno-builtin",
          "-fno-stack-protector", "-ffunction-sections", "-fdata-sections",
          "-Wall", "-Wextra", "-Werror=implicit-function-declaration",
          "-fno-pic", "-mcpu=cortex_m4", "-mfloat-abi=soft",
          "-target", "thumb-freestanding-eabi"]
ZIG = [sys.executable, "-m", "ziglang"]


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=RAIZ)
    if r.returncode:
        sys.stderr.write(r.stdout + r.stderr)
        raise SystemExit("failed: " + " ".join(cmd[:4]))
    if r.stderr.strip():
        sys.stderr.write(r.stderr)
    return r.stdout


def compile_obj(src, incs, obj):
    os.makedirs(os.path.dirname(obj), exist_ok=True)
    run([*ZIG, "cc", *COMMON, *incs, "-c", src, "-o", obj])


def link(objs, elf, binf):
    run([*ZIG, "cc", *COMMON, *objs, "-nostdlib", "-static",
         "-Wl,--gc-sections", f"-Wl,-e,{HOOK}",
         "-Wl,--build-id=none", "-T", os.path.join(SDK, "app.ld"),
         "-o", elf])
    extract_section(elf, ".text", binf)


def extract_section(path, name, out):
    """Write one ELF section as a flat binary (zig objcopy is broken here)."""
    d = open(path, "rb").read()
    shoff, = struct.unpack_from("<I", d, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 0x2E)
    secs = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize)
            for i in range(shnum)]
    strtab = secs[shstrndx]
    for s in secs:
        n = d[strtab[4] + s[0]:d.index(0, strtab[4] + s[0])].decode()
        if n == name:
            with open(out, "wb") as f:
                f.write(d[s[4]:s[4] + s[5]])
            return
    raise SystemExit(f"secao {name} nao encontrada em {path}")


def elf_sections(path):
    d = open(path, "rb").read()
    shoff, = struct.unpack_from("<I", d, 0x20)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", d, 0x2E)
    secs = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize)
            for i in range(shnum)]
    strtab = secs[shstrndx]
    out = {}
    for s in secs:
        name = s[0]
        n = d[strtab[4] + name:d.index(0, strtab[4] + name)].decode()
        out[n] = s
    return d, secs, out


def elf_symbols(path):
    d = open(path, "rb").read()
    shoff, = struct.unpack_from("<I", d, 0x20)
    shentsize, shnum = struct.unpack_from("<HH", d, 0x2E)
    secs = [struct.unpack_from("<IIIIIIIIII", d, shoff + i * shentsize)
            for i in range(shnum)]
    out = {}
    for s in secs:
        if s[1] != 2:  # SHT_SYMTAB
            continue
        strtab = secs[s[6]]
        for o in range(s[4], s[4] + s[5], 16):
            name, value, _size, _info, _other, shndx = struct.unpack_from(
                "<IIIBBH", d, o)
            if name and shndx:
                n = d[strtab[4] + name:d.index(0, strtab[4] + name)].decode()
                out[n] = value
    return out


def _rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def png_header(src, out, name):
    from PIL import Image
    im = Image.open(src).convert("RGBA")
    w, h = im.size
    alpha = im.getchannel("A").tobytes()
    chroma = any(a < 128 for a in alpha)
    raw = im.tobytes()
    data = bytearray()
    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i:i + 4]
        if chroma and a < 128:
            v = 0x07E0  # LV_COLOR_CHROMA_KEY
        else:
            v = _rgb565(r, g, b)
            if chroma and v == 0x07E0:
                v = 0x07C0
        data += struct.pack(">H", v)
    lines = [
        f"/* Generated by tools/build_sdk.py from {os.path.basename(src)} */",
        "#pragma once",
        '#include "fw.h"',
        "",
        f"static const uint8_t {name}_data[{len(data)}] = {{",
    ]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines += [
        "};",
        "",
        f"static const lv_img_dsc_t {name} = {{",
        f"\t.header = LV_IMG_HEADER({'LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED' if chroma else 'LV_IMG_CF_TRUE_COLOR'}, {w}, {h}),",
        f"\t.data_size = sizeof({name}_data),",
        f"\t.data = {name}_data,",
        "};",
        "",
    ]
    with open(out, "w", newline="\n") as f:
        f.write("\n".join(lines))


def sources(variante):
    incs = ["-I", os.path.join(SDK, "include")]
    apps = []
    if variante == "diag":
        apps.append(os.path.join(SDK, "apps/keytest"))
        incs += ["-DFW_DIAG"]
    elif variante == "jogos":
        apps += [os.path.join(SDK, "apps/flutter"), os.path.join(SDK, "apps/mp3tris")]
    else:
        raise SystemExit("variante deve ser diag ou jogos")
    return incs, apps


def build(variante, outdir):
    if os.path.isdir(outdir):
        shutil.rmtree(outdir)
    os.makedirs(outdir)
    incs, apps = sources(variante)
    gen = os.path.join(outdir, "gen")
    os.makedirs(gen)

    if variante == "jogos":
        assets = os.path.join(SDK, "apps/flutter/assets")
        for f in sorted(os.listdir(assets)):
            if f.endswith(".png"):
                png_header(os.path.join(assets, f), os.path.join(gen, f[:-4] + ".h"),
                           "img_" + f[:-4])

    objs = []
    for app in apps:
        name = os.path.basename(app)
        for f in sorted(os.listdir(app)):
            if f.endswith(".c"):
                obj = os.path.join(outdir, "obj", name, f[:-2] + ".o")
                compile_obj(os.path.join(app, f), [*incs, "-I", app, "-I", gen], obj)
                objs.append(obj)
    for f in sorted(os.listdir(os.path.join(SDK, "src"))):
        if f.endswith(".c"):
            obj = os.path.join(outdir, "obj", "sdk", f[:-2] + ".o")
            compile_obj(os.path.join(SDK, "src", f), incs, obj)
            objs.append(obj)

    elf = os.path.join(outdir, "app.elf")
    binf = os.path.join(outdir, "app.bin")
    link(objs, elf, binf)

    _, _, secs = elf_sections(elf)
    for n in (".data", ".bss"):
        sz = secs[n][5] if n in secs else 0
        if sz:
            raise SystemExit(f"{n} tem {sz} bytes; escreva estado em lv_mem_alloc")
    elf_data = open(elf, "rb").read()
    entry = struct.unpack_from("<I", elf_data, 0x18)[0]
    if not (entry & 1):
        raise SystemExit("e_entry sem bit Thumb; o linker nao marcou o gancho")
    hook = entry & ~1
    size = os.path.getsize(binf)
    if size > 0x51000:
        raise SystemExit(f"SDK com {size} bytes nao cabe no lote 0x1AB000..0x1FC000")
    info = {
        "variante": variante,
        "load": BASE,
        "flash_offset": BASE - FLASH,
        "size": size,
        "sha256": hashlib.sha256(open(binf, "rb").read()).hexdigest(),
        "hook": hook,
        "hook_symbol": HOOK,
    }
    with open(os.path.join(outdir, "app.json"), "w") as f:
        json.dump(info, f, indent=1)
    return info, binf


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--variante", choices=("diag", "jogos"), default="jogos")
    ap.add_argument("--out-dir", default=os.path.join(SDK, "build", "sdk"))
    ap.add_argument("--check-repro", action="store_true")
    a = ap.parse_args()
    out = os.path.abspath(a.out_dir)
    info, _ = build(a.variante, out)
    print(f"SDK {info['variante']}: {info['size']} bytes em 0x{info['load']:08X}, "
          f"hook 0x{info['hook']:08X}, sha {info['sha256'][:16]}...")
    if a.check_repro:
        out2 = out + "_repro"
        info2, _ = build(a.variante, out2)
        if info["sha256"] != info2["sha256"]:
            raise SystemExit("REPRODUTIBILIDADE FALHOU: binarios diferentes")
        print(f"reprodutivel: {info2['sha256'][:16]}...")
    return 0


if __name__ == "__main__":
    sys.exit(main())
